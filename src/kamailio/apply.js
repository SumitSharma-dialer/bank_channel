'use strict';
// DB -> files in /etc/kamailio/sipdist -> Kamailio RPC reload. The Kamailio twin of src/asterisk/apply.js.
// data.lua (trunks, processes, DIDs) reloads live; kamailio.cfg / rtpengine.conf only change with .env or an app
// update and need an engine restart (System → SIP engine).
const fs = require('fs/promises');
const path = require('path');
const dns = require('dns').promises;
const { execFile } = require('child_process');
const cfg = require('../config');
const { q } = require('../db');
const { rpc, key } = require('./rpc');
const R = require('./render');

let chain = Promise.resolve();
let last = { at: null, ok: null, error: null, reloaded: [], restartNeeded: false };
const IP_RE = /^(?:\d{1,3}\.){3}\d{1,3}$/;

// this server's main IPv4 address (the one Asterisk answers from)
let ownIp = null;
function selfIp() {
  if (cfg.kamailio.listenIp) return Promise.resolve(cfg.kamailio.listenIp);
  if (ownIp) return Promise.resolve(ownIp);
  return new Promise((resolve, reject) => {
    execFile('ip', ['-o', 'route', 'get', '1.1.1.1'], { timeout: 2000 }, (err, out) => {
      const ip = (/\bsrc (\d+\.\d+\.\d+\.\d+)/.exec(out || '') || [])[1];
      if (err || !ip) return reject(new Error('cannot find this server\'s IP address — set KAMAILIO_LISTEN_IP in .env'));
      resolve(ownIp = ip);
    });
  });
}

async function loadRows() {
  const trunks = (await q('SELECT * FROM trunks ORDER BY name')).rows;
  const processes = (await q('SELECT * FROM processes ORDER BY code')).rows;
  const ranges = (await q('SELECT * FROM trunk_did_ranges ORDER BY trunk_id, first_did')).rows;
  for (const t of trunks) t.did_ranges = ranges.filter((r) => r.trunk_id === t.id);
  const rejectCodes = {};
  for (const d of (await q(`SELECT code, sip_code FROM dispositions WHERE source='distributor'`)).rows) rejectCodes[d.code] = d.sip_code;
  return { trunks, processes, rejectCodes };
}

async function options() {
  const ip = await selfIp();
  const u = new URL(cfg.redisUrl);
  return { selfIp: ip, advertiseIp: cfg.kamailio.advertiseIp, sipPort: cfg.sipPort, rpcPort: cfg.kamailio.rpcPort, ngPort: cfg.kamailio.ngPort,
    dir: cfg.kamailio.confDir, children: cfg.kamailio.children, realm: 'asterisk', rpcKey: key, maskKey: key.slice(0, 16),
    evKey: cfg.kamailio.evKey, sizesKey: cfg.kamailio.sizesKey, routeUrl: `http://127.0.0.1:${cfg.http.port}/internal/did-route`,
    redis: { host: u.hostname, port: +u.port || 6379, pass: decodeURIComponent(u.password || '') }, rtpStart: cfg.rtp.start, rtpEnd: cfg.rtp.end };
}

async function renderAll() {
  const { trunks, processes, rejectCodes } = await loadRows();
  const o = { ...(await options()), rejectCodes, hostIps: {} };
  // trunk hosts given as names: Kamailio identifies carriers by source IP, so resolve them here
  for (const t of trunks.filter((x) => x.active && !IP_RE.test(String(x.host).trim()))) {
    o.hostIps[String(t.host).trim()] = await dns.lookup(String(t.host).trim(), { all: true, family: 4 }).then((a) => a.map((x) => x.address), () => []);
  }
  return {
    'data.lua': R.renderData(trunks, processes, o),
    'dispatcher.list': R.renderDispatcher(trunks, processes),
    'dbtext/uacreg': R.renderUacreg(trunks, o),
    'dbtext/version': R.renderDbVersion(),
    'kamailio.cfg': R.renderCfg(o),
    'rtpengine.conf': R.renderRtpengine(o),
    'sipdist.lua': await fs.readFile(path.join(__dirname, 'sipdist.lua'), 'utf8'),
  };
}

// the "GENERATED ... at <time>" line changes on every render: ignore it when asking "did this file change?"
const body = (t) => String(t).replace(/^.*GENERATED by SIP Channel Distributor at .*$/m, '');
async function writeChanged(file, text) {
  const cur = await fs.readFile(file, 'utf8').catch(() => null);
  if (cur !== null && body(cur) === body(text)) return false;
  const tmp = `${file}.tmp-${process.pid}`;
  await fs.writeFile(tmp, text, { mode: 0o640 });
  await fs.rename(tmp, file);
  return true;
}

// RPC to run when a file changed
const RELOAD = { 'data.lua': 'app_lua.reload', 'sipdist.lua': 'app_lua.reload', 'dispatcher.list': 'dispatcher.reload', 'dbtext/uacreg': 'uac.reg_reload' };
const RESTART = new Set(['kamailio.cfg', 'rtpengine.conf']);

// opts.reload false = only write the files (before the engine is started); opts.force = reload everything
async function doApply(reason, opts = {}) {
  const files = await renderAll();
  await fs.mkdir(path.join(cfg.kamailio.confDir, 'dbtext'), { recursive: true });
  const changed = [];
  for (const [name, text] of Object.entries(files)) {
    if (await writeChanged(path.join(cfg.kamailio.confDir, name), text)) changed.push(name);
  }
  const reloaded = [];
  let restartNeeded = opts.reload === false ? false : last.restartNeeded || changed.some((f) => RESTART.has(f));
  if (cfg.kamailio.reload && opts.reload !== false) {
    const todo = new Set((opts.force ? Object.keys(RELOAD) : changed).map((f) => RELOAD[f]).filter(Boolean));
    for (const m of todo) { await rpc(m); reloaded.push(m); }
  }
  last = { at: new Date().toISOString(), ok: true, error: null, reloaded, reason, restartNeeded };
  console.log(`[apply] kamailio ${reason}: wrote ${changed.join(', ') || 'nothing new'}; reloaded ${reloaded.join(', ') || 'nothing'}`);
  return last;
}

function apply(reason = 'manual', opts) {
  const p = chain.then(() => doApply(reason, opts)).catch((e) => {
    last = { at: new Date().toISOString(), ok: false, error: e.message, reloaded: [], reason, restartNeeded: last.restartNeeded };
    console.error('[apply] kamailio failed:', e.message);
    return last;
  });
  chain = p;
  return p;
}

// config preview for the System page: secrets are never shown
async function preview() {
  const f = await renderAll();
  const hide = (t) => t.replace(/(\["(?:pass|rpc_key)"\] = )"[^"]*"/g, '$1"***"').replace(/(;pass=)[^"]*/g, '$1***').replace(/("mask_key", )"[^"]*"/, '$1"***"');
  return { 'data.lua': hide(f['data.lua']), 'dispatcher.list': f['dispatcher.list'], 'kamailio.cfg': hide(f['kamailio.cfg']), 'rtpengine.conf': f['rtpengine.conf'] };
}

module.exports = { apply, renderAll, preview, selfIp, status: () => last };
